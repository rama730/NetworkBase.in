// Installers for the single-file nb (report C7): the Homebrew formula and the Scoop manifest, written from a
// release's files and checksums. The release workflow runs it in the public tap repository (vars.NB_TAP_REPO), which
// holds the downloads, Formula/nb.rb (brew install <owner>/networkbase/nb) and bucket/nb.json (a Scoop bucket).
//   node scripts/packages.mjs <version> <tap repo, owner/name> <dir with nb-* files and nb-*.sha256>
import fs from "node:fs";
import path from "node:path";

const LICENSE = JSON.parse(fs.readFileSync(new URL("../package.json", import.meta.url), "utf8")).license;

/** @param {string} version @param {string} repo @param {Record<string, string>} sums file name → sha256 */
export function homebrewFormula(version, repo, sums) {
  const url = (/** @type {string} */ f) => `https://github.com/${repo}/releases/download/v${version}/${f}`;
  const need = (/** @type {string} */ f) => { if (!sums[f]) throw new Error(`No checksum for ${f}`); return sums[f]; };
  return `# Generated by packages/nb-cli/scripts/packages.mjs for nb ${version}. Do not edit.
class Nb < Formula
  desc "NetworkBase CLI: your workspaces, tasks and files from the terminal"
  homepage "https://networkbase.in/docs/cli"
  version "${version}"
  license "${LICENSE}"

  # Apple silicon only for now: there's no Intel Mac build (macOS Intel runners are gone from CI).
  depends_on arch: :arm64 if OS.mac?

  on_macos do
    on_arm do
      url "${url("nb-macos-arm64")}"
      sha256 "${need("nb-macos-arm64")}"
    end
  end
  on_linux do
    on_intel do
      url "${url("nb-linux-x64")}"
      sha256 "${need("nb-linux-x64")}"
    end
  end

  def install
    bin.install Dir["nb-*"].first => "nb"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/nb --version")
  end
end
`;
}

/** @param {string} version @param {string} repo @param {Record<string, string>} sums */
export function scoopManifest(version, repo, sums) {
  const file = "nb-windows-x64.exe";
  if (!sums[file]) throw new Error(`No checksum for ${file}`);
  return `${JSON.stringify({
    version,
    description: "NetworkBase CLI: your workspaces, tasks and files from the terminal",
    homepage: "https://networkbase.in/docs/cli",
    license: LICENSE,
    architecture: { "64bit": { url: `https://github.com/${repo}/releases/download/v${version}/${file}#/nb.exe`, hash: sums[file] } },
    bin: "nb.exe",
    checkver: { github: `https://github.com/${repo}` },
    autoupdate: { architecture: { "64bit": { url: `https://github.com/${repo}/releases/download/v$version/${file}#/nb.exe` } } },
  }, null, 2)}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [version, repo, dir] = process.argv.slice(2);
  if (!version || !repo || !dir) throw new Error("node scripts/packages.mjs <version> <owner/name> <dir>");
  /** @type {Record<string, string>} */
  const sums = {};
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".sha256"))) sums[f.replace(/\.sha256$/, "")] = fs.readFileSync(path.join(dir, f), "utf8").trim().split(/\s+/)[0] ?? "";
  fs.mkdirSync("Formula", { recursive: true });
  fs.mkdirSync("bucket", { recursive: true });
  fs.writeFileSync("Formula/nb.rb", homebrewFormula(version, repo, sums));
  fs.writeFileSync("bucket/nb.json", scoopManifest(version, repo, sums));
  console.log(`Formula/nb.rb and bucket/nb.json for nb ${version}`);
}
